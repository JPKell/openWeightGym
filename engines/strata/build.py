"""Read-only Strata installation identity; never build, install, or load a GPU model."""
import json
import os
import platform
from pathlib import Path
import re
import subprocess

from engines.strata.artifacts import digest, identity
from engines.strata.config import NodeSettings
from engines.strata.runtime import REVISION, verify_source

# A fresh per-launch cache prefix plus -B prevents unrecorded bytecode overriding sources.
PYTHON_POLICY = "isolated-no-bytecode-fresh-cache-v1"


def python_command(python: str, script: str, private_directory: str, *arguments: str) -> list[str]:
    """Return the Python command for the controlled Strata worker."""
    cache = Path(private_directory)/"python-cache"
    cache.mkdir(mode=0o700)  # fail rather than reuse an existing bytecode cache
    return [python, "-I", "-B", "-X", f"pycache_prefix={cache}", script, *arguments]


def linked_files(paths: list[Path]) -> list[Path]:
    """Inspect the reviewed local binaries, including dependencies of Python extensions."""
    found = set()
    env = {"PATH": os.defpath, "LC_ALL": "C"}
    for path in paths:
        result = subprocess.run(["ldd", str(path)], env=env, capture_output=True, text=True, timeout=15)
        if result.returncode or "not found" in result.stdout:
            raise ValueError("Strata runtime shared-library dependencies are unavailable.")
        for line in result.stdout.splitlines():
            match = re.search(r"(?:=>\s+|^\s*)(/\S+)\s+\(", line)
            if match:
                found.add(Path(match[1]).resolve(strict=True))
    # CUDA loads its driver dynamically, so it is not necessarily in ldd's output.
    cache = subprocess.run(["/sbin/ldconfig", "-p"], env=env, capture_output=True, text=True, timeout=15, check=True)
    drivers = [Path(line.split("=>", 1)[1].strip()) for line in cache.stdout.splitlines()
               if line.strip().startswith("libcuda.so.1 ") and "x86-64" in line]
    if len(drivers) != 1:
        raise ValueError("Strata requires one unambiguous native CUDA driver library.")
    found.add(drivers[0].resolve(strict=True))
    return sorted(found)


def tree_files(root: Path) -> list[Path]:
    """Inference code/data, not generated bytecode, VCS objects or build output."""
    return sorted(path for path in root.rglob("*") if path.is_file() and
                  not {"__pycache__", ".git"} & set(path.relative_to(root).parts) and path.suffix != ".pyc")


def manifest(node: NodeSettings) -> dict:
    """Read the qualified runtime build manifest."""
    node.check_paths()
    source = Path(node.source)
    verify_source(source)
    # -S prevents .pth/site hooks before their content has been inventoried.
    inspected = subprocess.run([node.python, "-I", "-S", "-c",
        "import json,sys,sysconfig;print(json.dumps({'version':sys.version,'stdlib':sysconfig.get_path('stdlib')}))"],
        capture_output=True, text=True, timeout=15, check=True,
        env={"PATH": os.defpath, "LANG": "C.UTF-8"})
    python = json.loads(inspected.stdout)
    stdlib = Path(python["stdlib"])
    venv = Path(node.python).parent.parent
    native = Path(node.executable)
    files = {"native": native, "native_kq": native.with_name("libstrata_kq.so"),
             "python": Path(node.python).resolve(strict=True), "venv_config": venv/"pyvenv.cfg"}
    tracked = subprocess.run(["git", "-C", str(source), "ls-files", "-z"], check=True, capture_output=True).stdout
    for name in tracked.decode().split("\0"):
        if name:
            files["upstream/"+name] = source/name
    for label, folder in (("environment", venv/"lib"), ("stdlib", stdlib)):
        for path in tree_files(folder):
            if label == "environment" and path.suffix == ".pth":
                for line in path.read_text().splitlines():
                    if line.strip() and not line.startswith(("#", "import ", "import\t")) \
                            and not (path.parent/line.strip()).resolve().is_relative_to(venv.resolve()):
                        raise ValueError("Strata's private environment may not import untracked external .pth paths.")
            files[label+"/"+str(path.relative_to(folder))] = path
    suite = Path(__file__).resolve().parents[2]
    for package in ("engines", "loadcoach"):
        for path in tree_files(suite/package):
            if path.suffix in (".py", ".json"):
                files["suite/"+str(path.relative_to(suite))] = path
    zip_path = stdlib.parent/(stdlib.name.replace(".", "")+".zip")
    if zip_path.exists():
        files["stdlib_zip"] = zip_path
    for path in linked_files([native, files["native_kq"], files["python"],
                              *[path for label, path in files.items() if label.startswith(("environment/", "stdlib/")) and path.suffix == ".so"]]):
        files["linked/"+str(path)] = path
    entries = {label: identity(str(path.absolute())) for label, path in sorted(files.items())}
    inputs = {label: entry["sha256"] for label, entry in entries.items()}
    # Verification repeats inventory, so added/deleted files and dependency changes invalidate.
    value = {"schema": 1, "engine": "strata", "revision": REVISION, "python": python["version"],
             "python_policy": PYTHON_POLICY, "kernel": platform.release(),
             "host_ram_mib": node.host_ram_mib, "allow_host_ram": node.allow_host_ram,
             "nvidia_kernel": Path("/proc/driver/nvidia/version").read_text() if Path("/proc/driver/nvidia/version").exists() else "unavailable",
             "files": entries}
    value["sha256"] = digest({**{key: item for key, item in value.items() if key != "files"}, "files": inputs})
    return value


def verify(node: NodeSettings, expected: dict) -> dict:
    """Verify that the installed runtime matches its reviewed build manifest."""
    current = manifest(node)
    if current != expected:
        raise ValueError("Strata installation changed; prepare and qualify this build again.")
    return current
